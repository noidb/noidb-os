const assert = require("node:assert/strict");
const { createHarness, state, progress, snapshot } = require("./verify-weekly-work-route.cjs");

(async () => {
  const importedWorkspace=state.emptyWeeklyWorkspace();
  const importedRun=state.addWeeklyRun(importedWorkspace,snapshot());
  importedRun.reviews['2001'].decision='discontinue';
  const evidence={skuId:'2001',productName:importedRun.snapshot.vendorItems.find(i=>i.skuId==='2001').productName,requestId:'2710831275',submittedAt:'2026-09-08T15:34:16+09:00'};
  const clock='2026-09-09T00:00:00Z';
  const pristine=JSON.stringify(importedWorkspace);
  assert.throws(()=>state.recordWeeklyDiscontinueHistory(importedWorkspace,importedRun,[evidence,{...evidence,skuId:'9999'}],'operator evidence',clock));
  assert.equal(JSON.stringify(importedWorkspace),pristine,'invalid whole batch has no partial mutation');
  assert.equal(state.recordWeeklyDiscontinueHistory(importedWorkspace,importedRun,[evidence],'operator evidence',clock),1);
  assert.equal(state.recordWeeklyDiscontinueHistory(importedWorkspace,importedRun,[evidence],'operator evidence',clock),0,'request replay does not append');
  assert.equal(JSON.stringify(importedRun.discontinueSubmittedSkuIds),JSON.stringify(['2001']));
  assert.equal(importedRun.reorderRequestedAt,undefined,'import does not complete reorders');
  const importedNext=state.addWeeklyRun(importedWorkspace,{...snapshot(),id:'after-import'});
  assert(!progress.weeklyReviewIsActive(importedNext,importedNext.reviews['2001']),'imported submission blocks repeat review');
  const workspace = state.emptyWeeklyWorkspace();
  const old = state.addWeeklyRun(workspace, snapshot());
  old.couponUploadedAt = "2026-09-08T00:35:04Z";
  old.couponExpiresOn = "2026-09-20";
  const fresh = { ...snapshot(), id: "new-receipt", couponReceiptKeys: { "1001": ["new-event"] } };
  const beforeEnd = new Date("2026-09-20T14:59:59Z");
  const afterEnd = new Date("2026-09-20T15:00:00Z");
  assert.equal(state.eligibleWeeklyCoupons(workspace, fresh, fresh.id, beforeEnd).couponItems.length, 0, "KST end date is inclusive");
  assert.equal(state.eligibleWeeklyCoupons(workspace, fresh, fresh.id, afterEnd).couponItems.length, 1, "new receipt eligible after end date");
  assert.equal(state.eligibleWeeklyCoupons(workspace, { ...fresh, couponReceiptKeys: old.snapshot.couponReceiptKeys }, fresh.id, afterEnd).couponItems.length, 0, "expiry never reissues the same receipt");
  delete old.couponExpiresOn;
  assert.equal(state.eligibleWeeklyCoupons(workspace, fresh, fresh.id, afterEnd).couponItems.length, 0, "unknown expiry blocks repeat SKU");
  state.recordWeeklyCouponChecks(workspace, [{ skuId: "1001", expiresOn: "2026-09-20" }, { skuId: "1001", expiresOn: "2026-09-19" }], "verified all SKU coupons", "2026-09-21T00:00:00Z");
  assert.equal(workspace.couponChecks.length, 1);
  assert.equal(workspace.couponChecks[0].expiresOn, "2026-09-20", "latest expiry wins in a pasted batch");
  assert.equal(state.weeklyCouponBlocks(workspace, fresh.id, afterEnd).length, 0, "verified end date resolves legacy unknown expiry");
  assert.throws(() => state.recordWeeklyCouponChecks(workspace, [{skuId:"1001",expiresOn:"2026-02-30"}], "bad"), /종료일/);
  assert.throws(() => state.recordWeeklyCouponChecks(workspace, [{skuId:"1e8",expiresOn:"2026-09-20"}], "bad"), /SKU/);
  const newer = state.addWeeklyRun(workspace, { ...fresh, id: "later-registration" });
  newer.snapshot.couponItems = snapshot().couponItems;
  newer.couponUploadedAt = "2026-09-22T00:00:00Z";
  newer.couponExpiresOn = "2026-10-10";
  assert.equal(state.weeklyCouponBlocks(workspace, fresh.id, new Date("2026-09-23")).length, 1, "later registration survives older verified state");

  const vendors = state.emptyWeeklyWorkspace();
  const prior = state.addWeeklyRun(vendors, snapshot());
  prior.discontinueSubmittedAt = "2026-09-08";
  prior.discontinueSubmittedSkuIds = ["2001"];
  const next = state.addWeeklyRun(vendors, { ...snapshot(), id: "next-week" });
  assert(!progress.weeklyReviewIsActive(next, next.reviews["2001"]), "prior discontinued SKU leaves recurring active review");
  assert.equal(state.weeklySelectedOrders(next).length, 0, "hidden completion also excluded from vendor file");
  next.reviews["2001"].decision = "discontinue";
  assert(!progress.weeklyReviewIsActive(next, next.reviews["2001"]), "stale prior decision cannot reopen completed discontinuation");
  next.discontinueQueueRequestIds = {"2001":["explicit-new-request"]};
  assert(!progress.weeklyReviewIsActive(next, next.reviews["2001"]), "linked pending request is processed only in the common status queue");
  assert(!progress.weeklyReviewCompletion(next, next.reviews["2001"]), "transfer is not external completion");
  const reorder = state.addWeeklyRun(state.emptyWeeklyWorkspace(), snapshot());
  reorder.snapshot.vendorItems[0].shortageDetails = [{purchaseOrderNumber:"123",confirmedQuantity:5,receivedQuantity:3,shortageQuantity:2}];
  reorder.reorderPreviouslyRequestedLines = [{purchaseOrderNumber:"123",skuId:"2001",shortageQuantity:2}];
  assert(!progress.weeklyReviewIsActive(reorder, reorder.reviews["2001"]));
  reorder.snapshot.vendorItems[0].shortageDetails.push({purchaseOrderNumber:"456",confirmedQuantity:4,receivedQuantity:3,shortageQuantity:1});
  assert(progress.weeklyReviewIsActive(reorder, reorder.reviews["2001"]), "different PO remains visible even for same SKU");
  const staleWorkspace = state.emptyWeeklyWorkspace();
  const opened = state.addWeeklyRun(staleWorkspace, snapshot());
  const doneElsewhere = state.addWeeklyRun(staleWorkspace, {...snapshot(),id:"another-window"});
  doneElsewhere.discontinueSubmittedSkuIds=["2001"];
  assert.throws(()=>state.assertWeeklyReviewEligibility(staleWorkspace,opened),/이미 단종/ ,"stale window cannot dispatch a newly completed SKU");

  const h = createHarness(); const run = await h.analyze();
  const out = await h.output({runId:run.id,expectedRevision:run.revision,kind:"coupon"});
  const gen = await h.post({action:"generated",runId:run.id,expectedRevision:run.revision,outputKey:out.headers["X-NOIDB-Output-Key"]});
  const missingDate = await h.post({action:"status",kind:"coupon",runId:run.id,expectedRevision:gen.body.run.revision});
  assert.equal(missingDate.status, 409); assert.match(missingDate.body.error, /종료일/);
  const oldRevision = h.workspace().revision;
  const saved = await h.post({action:"coupon-history",expectedRevision:oldRevision,rows:[{skuId:"1001",expiresOn:"2099-12-31"}],source:"verified coupon page"});
  assert.equal(saved.status, 200);
  assert.equal((await h.post({action:"coupon-history",expectedRevision:oldRevision,rows:[{skuId:"1001",expiresOn:"2000-01-01"}],source:"stale window"})).status,409);
  assert.equal((await h.output({runId:run.id,expectedRevision:gen.body.run.revision,kind:"coupon"})).status,409,"cached file cannot bypass new coupon history");
  console.log("PASS recurring weekly work: SKU expiry, KST boundary, receipt identity, legacy reconciliation, later registrations, prior completion visibility, different PO, expiry required, CAS and cached output guard. Fixtures only.");
})().catch(error => { console.error(error); process.exitCode = 1; });
